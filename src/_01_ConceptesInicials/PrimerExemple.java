package _01_ConceptesInicials;

public class PrimerExemple {
    public static void main(String[] args) {
// Dades del programa
        String nom = "Anna";
        int edat = 18;
        double nota = 7.5;
        boolean aprovat = true;
// Fem una operació
        int edatAnyQueVe = edat + 1;
// Mostrem informació
        System.out.println("Hola " + nom);
        System.out.println("Tens " + edat + " anys.");
        System.out.println("L'any que ve tindràs " + edatAnyQueVe + ".");
        System.out.println("La teua nota és " + nota);
        System.out.println("Has aprovat? " + aprovat);
    }
}
